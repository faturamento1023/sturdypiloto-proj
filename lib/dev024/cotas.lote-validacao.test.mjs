import test from 'node:test';
import assert from 'node:assert/strict';
import {avaliarCota} from './cotas.mjs';
const pedido={unidadeId:'u1',convenioId:'c1',procedimentoId:'p1',grupoId:'g1',inicio:'2026-11-09T12:30:00Z'};
const regra={id:'r1',unidadeId:'u1',limite:1,intervaloMinutos:60};
test('reserva ativa malformada falha mesmo sem regras',()=>assert.throws(()=>avaliarCota({regras:[],reservas:[{...pedido,inicio:'sem-data'}],pedido}),TypeError));
test('reserva ativa malformada falha mesmo com regra de outra unidade',()=>assert.throws(()=>avaliarCota({regras:[{...regra,unidadeId:'u2'}],reservas:[{...pedido,inicio:'2026-11-09T12:30:00'}],pedido}),TypeError));
test('reserva nula falha mesmo sem regras',()=>assert.throws(()=>avaliarCota({regras:[],reservas:[null],pedido}),TypeError));
test('reserva cancelada sem data continua ignorada',()=>assert.equal(avaliarCota({regras:[regra],reservas:[{status:'cancelada'}],pedido}).permitido,true));
test('reserva válida mantém contagem',()=>assert.equal(avaliarCota({regras:[regra],reservas:[pedido],pedido}).permitido,false));
