import test from 'node:test';
import assert from 'node:assert/strict';
import {avaliarCota} from './cotas.mjs';
const pedido={unidadeId:'u1',convenioId:'c1',procedimentoId:'p1',grupoId:'g1',inicio:'2026-11-09T12:30:00Z'};
const regra={id:'r1',unidadeId:'u1',convenioId:'c1',limite:1,intervaloMinutos:60};
test('cota esgotada',()=>assert.equal(avaliarCota({regras:[regra],reservas:[pedido],pedido}).permitido,false));
test('cancelamento libera',()=>assert.equal(avaliarCota({regras:[regra],reservas:[{...pedido,status:'cancelada'}],pedido}).permitido,true));
test('unidades isoladas',()=>assert.equal(avaliarCota({regras:[regra],reservas:[{...pedido,unidadeId:'u2'}],pedido}).permitido,true));
test('regra restritiva prevalece',()=>assert.equal(avaliarCota({regras:[regra,{...regra,id:'r2',limite:0}],reservas:[],pedido}).permitido,false));
test('limite superior exclusivo',()=>assert.equal(avaliarCota({regras:[regra],reservas:[{...pedido,inicio:'2026-11-09T13:00:00Z'}],pedido}).permitido,true));
test('limite negativo rejeitado',()=>assert.throws(()=>avaliarCota({regras:[{...regra,limite:-1}],reservas:[],pedido}),TypeError));
